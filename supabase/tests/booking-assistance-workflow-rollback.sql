begin;
do $$
declare
  v_customer_id uuid := gen_random_uuid();
  v_staff_id uuid := gen_random_uuid();
  v_outsider_id uuid := gen_random_uuid();
  v_case_id uuid;
  v_closed_case_id uuid;
  v_expired_case_id uuid;
  v_application_id uuid;
  v_second_application_id uuid;
  v_closed_application_id uuid;
  v_revision bigint;
  n integer;
  blocked boolean;
begin
  if public.add_weekdays('2026-10-16'::date, 1) <> '2026-10-19'::date then raise exception 'FAIL: weekend business-day handling'; end if;
  insert into auth.users(id) values (v_customer_id), (v_staff_id), (v_outsider_id);
  insert into public.marketplace_staff(user_id) values (v_staff_id);

  perform set_config('request.jwt.claim.sub', v_customer_id::text, true); execute 'set local role authenticated';
  select id into v_case_id from public.create_booking_assistance_case(current_date + 40, 'Washington, DC', 90, 'Community celebration', 'Need an accessible venue with tables, parking, and a kitchen.');
  select count(*) into n from public.booking_assistance_fee_previews where booking_assistance_fee_previews.case_id = v_case_id and not fee_charged and preview_state = 'not_evaluated';
  if n <> 1 then raise exception 'FAIL: noncharging fee preview'; end if;

  perform set_config('request.jwt.claim.sub', v_outsider_id::text, true);
  select count(*) into n from public.booking_assistance_cases where id = v_case_id;
  if n <> 0 then raise exception 'FAIL: outsider read assistance case'; end if;
  blocked := false;
  begin perform public.add_booking_assistance_suggestion(v_case_id, 'Forged Venue', 'https://example.gov/forged', 'This suggestion should be blocked because the caller is not staff.'); exception when insufficient_privilege then blocked := true; end;
  if not blocked then raise exception 'FAIL: outsider added suggestion'; end if;

  perform set_config('request.jwt.claim.sub', v_staff_id::text, true);
  perform public.add_booking_assistance_suggestion(v_case_id, 'Venue One', 'https://example.gov/one', 'Fits the location, guest count, accessibility, and kitchen requirements.');
  perform public.add_booking_assistance_suggestion(v_case_id, 'Venue Two', 'https://example.gov/two', 'Offers parking and an appropriate room layout for the planned event.');
  perform public.add_booking_assistance_suggestion(v_case_id, 'Venue Three', 'https://example.gov/three', 'Provides the requested amenities and an official application process.');
  blocked := false;
  begin perform public.add_booking_assistance_suggestion(v_case_id, 'Venue Four', 'https://example.gov/four', 'This fourth suggestion exceeds the agreed service limit and must fail.'); exception when invalid_parameter_value then blocked := true; end;
  if not blocked then raise exception 'FAIL: more than three suggestions'; end if;
  select id, revision into v_application_id, v_revision from public.prepare_booking_assistance_application(v_case_id, 'Venue One', 'https://example.gov/one', 'Please consider this application for our community celebration with ninety guests and accessibility needs.', true, true);
  blocked := false;
  begin perform public.record_booking_assistance_submission(v_application_id); exception when no_data_found then blocked := true; end;
  if not blocked then raise exception 'FAIL: submitted without customer approval'; end if;

  perform set_config('request.jwt.claim.sub', v_customer_id::text, true);
  blocked := false;
  begin perform public.approve_booking_assistance_application(v_application_id, v_revision + 1); exception when serialization_failure then blocked := true; end;
  if not blocked then raise exception 'FAIL: customer approved a stale application revision'; end if;
  perform set_config('request.jwt.claim.sub', '', true);
  blocked := false;
  begin perform public.approve_booking_assistance_application(v_application_id, v_revision); exception when no_data_found then blocked := true; end;
  if not blocked then raise exception 'FAIL: authenticated role without a subject approved an application'; end if;
  perform set_config('request.jwt.claim.sub', v_customer_id::text, true);
  perform public.approve_booking_assistance_application(v_application_id, v_revision);
  blocked := false;
  begin perform public.record_booking_assistance_submission(v_application_id); exception when insufficient_privilege then blocked := true; end;
  if not blocked then raise exception 'FAIL: customer recorded submission'; end if;

  perform set_config('request.jwt.claim.sub', v_staff_id::text, true);
  perform public.record_booking_assistance_submission(v_application_id);
  blocked := false;
  begin perform public.prepare_booking_assistance_application(v_case_id, 'Venue Two', 'https://example.gov/two', 'This second application must wait until the submitted first application has a terminal outcome.', false, false); exception when invalid_parameter_value then blocked := true; end;
  if not blocked then raise exception 'FAIL: unresolved submitted application allowed a second application'; end if;
  perform public.record_booking_assistance_application_unsuccessful(v_application_id, 'Venue declined the submitted application.');
  select id, revision into v_second_application_id, v_revision from public.prepare_booking_assistance_application(v_case_id, 'Venue Two', 'https://example.gov/two', 'Please consider this second application after the first venue declined the event request.', true, true);

  perform set_config('request.jwt.claim.sub', v_customer_id::text, true);
  perform public.approve_booking_assistance_application(v_second_application_id, v_revision);
  perform set_config('request.jwt.claim.sub', v_staff_id::text, true);
  perform public.record_booking_assistance_submission(v_second_application_id);
  perform public.record_booking_assistance_followup(v_second_application_id);
  perform public.record_booking_assistance_followup(v_second_application_id);
  blocked := false;
  begin perform public.record_booking_assistance_followup(v_second_application_id); exception when invalid_parameter_value then blocked := true; end;
  if not blocked then raise exception 'FAIL: more than two follow-ups'; end if;
  blocked := false;
  begin perform public.confirm_booking_assistance_application(v_second_application_id, 'Written venue approval email received.', '', ''); exception when invalid_parameter_value then blocked := true; end;
  if not blocked then raise exception 'FAIL: confirmed without required payment and permit records'; end if;
  perform public.confirm_booking_assistance_application(v_second_application_id, 'Written venue approval email received and archived.', 'Receipt reference PAY-123 archived.', 'Permit reference PERMIT-456 archived.');
  select count(*) into n from public.booking_assistance_cases where id = v_case_id and status = 'confirmed' and confirmed_at is not null;
  if n <> 1 then raise exception 'FAIL: evidence-based confirmation'; end if;
  select count(*) into n from public.booking_assistance_fee_previews where booking_assistance_fee_previews.case_id = v_case_id and preview_state = 'proposed_eligible' and not fee_charged;
  if n <> 1 then raise exception 'FAIL: proposed fee outcome remained noncharging'; end if;
  blocked := false;
  begin perform public.prepare_booking_assistance_application(v_case_id, 'Venue Three', 'https://example.gov/three', 'A confirmed parent must never reopen for another application after confirmation.', false, false); exception when no_data_found then blocked := true; end;
  if not blocked then raise exception 'FAIL: confirmed parent reopened for another application'; end if;
  perform set_config('request.jwt.claim.sub', v_customer_id::text, true);
  blocked := false;
  begin perform public.close_booking_assistance_case(v_case_id, 'A confirmed case must remain terminal.'); exception when no_data_found then blocked := true; end;
  if not blocked then raise exception 'FAIL: customer changed a confirmed parent state'; end if;
  perform set_config('request.jwt.claim.sub', v_staff_id::text, true);
  blocked := false;
  begin perform public.record_booking_assistance_reversal(v_case_id, null); exception when no_data_found then blocked := true; end;
  if not blocked then raise exception 'FAIL: NULL reversal reason changed the confirmed parent state'; end if;
  perform public.record_booking_assistance_reversal(v_case_id, 'Venue cancelled before the event.');
  select count(*) into n from public.booking_assistance_fee_previews where booking_assistance_fee_previews.case_id = v_case_id and preview_state = 'proposed_refund_or_waiver' and not fee_charged;
  if n <> 1 then raise exception 'FAIL: noncharging reversal preview'; end if;

  perform set_config('request.jwt.claim.sub', v_customer_id::text, true);
  select id into v_closed_case_id from public.create_booking_assistance_case(current_date + 50, 'Silver Spring, MD', 40, 'Workshop', 'Need a classroom-style room with accessible transit and tables.');
  perform set_config('request.jwt.claim.sub', v_staff_id::text, true);
  perform public.add_booking_assistance_suggestion(v_closed_case_id, 'Workshop Hall', 'https://example.gov/workshop', 'The official source shows enough capacity, transit access, and classroom tables.');
  select id, revision into v_closed_application_id, v_revision from public.prepare_booking_assistance_application(v_closed_case_id, 'Workshop Hall', 'https://example.gov/workshop', 'Please consider this complete application for a forty-person workshop with accessible transit.', false, false);
  perform set_config('request.jwt.claim.sub', v_customer_id::text, true);
  perform public.approve_booking_assistance_application(v_closed_application_id, v_revision);
  blocked := false;
  begin perform public.close_booking_assistance_case(v_closed_case_id, null); exception when no_data_found then blocked := true; end;
  if not blocked then raise exception 'FAIL: NULL close reason changed the parent state'; end if;
  perform public.close_booking_assistance_case(v_closed_case_id, 'Customer changed plans before submission.');
  perform set_config('request.jwt.claim.sub', v_staff_id::text, true);
  blocked := false;
  begin perform public.record_booking_assistance_submission(v_closed_application_id); exception when no_data_found then blocked := true; end;
  if not blocked then raise exception 'FAIL: staff submitted an application after customer closure'; end if;
  blocked := false;
  begin perform public.confirm_booking_assistance_application(v_closed_application_id, 'Forged late venue approval.', '', ''); exception when no_data_found then blocked := true; end;
  if not blocked then raise exception 'FAIL: staff confirmed an application after customer closure'; end if;
  select count(*) into n from public.booking_assistance_cases where id = v_closed_case_id and status = 'closed' and confirmed_at is null;
  if n <> 1 then raise exception 'FAIL: closed parent state was not preserved'; end if;
  select count(*) into n from public.booking_assistance_fee_previews where booking_assistance_fee_previews.case_id = v_closed_case_id and preview_state = 'no_fee' and not fee_charged;
  if n <> 1 then raise exception 'FAIL: closed no-fee outcome was overwritten'; end if;

  perform set_config('request.jwt.claim.sub', v_customer_id::text, true);
  select id into v_expired_case_id from public.create_booking_assistance_case(current_date + 60, 'Arlington, VA', 25, 'Meeting', 'Need a small accessible room for a planning meeting and presentation.');
  execute 'reset role';
  update public.booking_assistance_cases set service_deadline = current_date - 1 where id = v_expired_case_id;
  perform set_config('request.jwt.claim.sub', v_staff_id::text, true); execute 'set local role authenticated';
  perform public.expire_booking_assistance_case(v_expired_case_id);
  blocked := false;
  begin perform public.add_booking_assistance_suggestion(v_expired_case_id, 'Late Venue', 'https://example.gov/late', 'An expired case must remain terminal even when staff attempts a late mutation.'); exception when no_data_found then blocked := true; end;
  if not blocked then raise exception 'FAIL: expired case accepted a later transition'; end if;
  select count(*) into n from public.booking_assistance_fee_previews where booking_assistance_fee_previews.case_id = v_expired_case_id and preview_state = 'no_fee' and not fee_charged;
  if n <> 1 then raise exception 'FAIL: expired no-fee outcome was not preserved'; end if;
end;
$$;
rollback;
select 'PASS: human review, immutable approval, sequential application outcomes, terminal parent locking, evidence confirmation, RLS, and noncharging fee previews; fixtures rolled back' as result;
